using System;
using Godot;

public partial class WorldItem : RigidBody3D, Interactable, Syncable
{
	[Signal] public delegate void PickedUpEventHandler();
	Node3D item_mesh;
	Globals globals;
	Node network;
	public static double spin_rate = 1.5;
	const float bob_distance = 0.0025f;
	int _server_id;
    public int server_id
	{
	get
		{
			return _server_id;
		}
	set
		{
			_server_id = value;
		}
	}

    public override void _Ready()
	{
		
		globals = GetNode<Globals>("/root/Globals");
		network = GetNode<Node>("/root/Network");

		PackedScene testmesh = GD.Load<PackedScene>("res://assets/glb/testmesh/TestShape.glb");
		item_mesh = testmesh.Instantiate<Node3D>();
		AddChild(item_mesh);
		SetMultiplayerAuthority(1);
		if (!Multiplayer.IsServer())
		{
			Freeze = true;
			network.Connect("on_worlditem_updated", Callable.From((int item_id, Vector3 pos, Vector3 rot) => RemoteSync(item_id, pos, rot)));
		}
	}

	void RemoteSync(int item_id, Vector3 pos, Vector3 rot)
	{
		if (item_id == server_id)
		{
			GlobalPosition = GlobalPosition.Lerp(pos, 0.75f);
			GlobalRotationDegrees = rot;
		}
	}

    public override void _PhysicsProcess(double delta)
    {
		item_mesh.RotateY(0.05f);
		Vector3 pos = item_mesh.Position;
		pos.Y += (float)Math.Sin(globals.world_item_spin_timer) * bob_distance;
		item_mesh.Position = pos;
		if (Multiplayer.IsServer())
		{
			network.Rpc("worlditem_updated", server_id, GlobalPosition, RotationDegrees);
		}
    }

	public Interactable.InteractableType GetInteractableType()
	{
		return Interactable.InteractableType.Item;
	}

	public void Interact()
	{
		EmitSignal(SignalName.PickedUp);
	}

	public string GetInteractPrompt()
	{
		return "Pickup [E]";
	}

}

